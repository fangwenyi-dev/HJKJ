# ── 禁入两族（第七轮审计 A7，v1.2.11）─────────────────────────────
# 这张表只该治"**同一个东西被听岔**"。它不该治"这话是谁说的"，也不该治
# "这句要做什么"——两族的差别是：前者错了只是听不懂，后者错了是**动了错的设备、
# 反了方向、凭空猜了房间**，正撞本仓红线（「没点名的设备任何方向都不动」「绝不
# 猜房间」）。现场两条实锤（.91 真地形跑生产码路）：
#   · 「打开我室的灯」→「打开卧室的灯」→ 真动卧室灯，而说话人在办公室；
#     「我室设备全部打开」更被折进区域批量道 = 整间房的设备按错的房间展开。
#   · 「把管灯打开」→「把关灯打开」→ 剥把后落 `关` 字头动作表 ⇒ **要开却下发关**。
#     同族「打开登录页面」→「打开灯录页面」→ t0 真产 TurnDeviceOn name=灯，
#     比「管灯」更高频（"登录"两字日常就在句子里）。
# 判据落在**键/值本身**（纯函数、不看句意）：代词开头的键一律禁、值是动作词的键
# 一律禁。用户手工扩展表（corrections_extra）同受此闸——那是它真正的价值：
# 基础表已经清干净之后，闸挡的是**下一次人往表里加错东西**（"关灯"的听岔救济
# 收益远小于把整句极性反掉的代价，这里要的是不冒，不是救回率）。
_PRONOUN_HEADS = frozenset("我你您他她它咱俺")
# 只收**开关极性/启停/锁**这类"改了它就等于改这句要做什么"的值。
# 刻意**不含**「调亮/调暗」：表内「条亮→调亮」「条案→调暗」治的是属性档位的
# 听岔，方向不变（「条案一点」只有当"调暗一点"这一种读法），闸把它杀掉就是
# 净回归——禁入族的判据是"会不会反转/凭空造出动作"，不是"值像不像动词"。
_ACTION_VALUES = frozenset({"关灯", "开灯", "打开", "关闭", "开启", "关掉", "关上",
                            "暂停", "启动", "停止", "上锁", "解锁"})


def _rejected_pair(wrong: str, right: str) -> bool:
    """这一对键值是否属于禁入族（代词开头 / 值是动作词）。永不抛。"""
    try:
        return bool(wrong) and (wrong[0] in _PRONOUN_HEADS or right in _ACTION_VALUES)
    except Exception:  # noqa: BLE001 判据故障=不替换（宁不改写，绝不动错设备）
        return True


def _at_word_start(text: str, idx: int) -> bool:
    """键起点 idx 是否落在词界（前一字是句首/非汉字/词尾字）。永不抛。"""
    if idx <= 0:
        return True
    ch = text[idx - 1]
    if not ("\u4e00" <= ch <= "\u9fff"):
        return True                    # 标点/数字/字母/空格天然词界
    return ch in _BOUNDARY_BEFORE


def _replace_whole(text: str, wrong: str, right: str) -> str:
    """只替换落在词界的整词命中；词内子串（"宿[舍灯]"）原样保留。"""
    out: list[str] = []
    i = 0
    while True:
        j = text.find(wrong, i)
        if j < 0:
            out.append(text[i:])
            return "".join(out)
        if _at_word_start(text, j):
            out.append(text[i:j])
            out.append(right)
        else:
            out.append(text[i:j + len(wrong)])
        i = j + len(wrong)


def apply(text: str, extra: dict[str, str] | None = None) -> str:
    """按「长键优先」顺序替换（基础表与新键合并；同名键基础表优先——基础表经
    数据集回归验证，用户扩展只做追加不做覆盖）。**只按词界替换**（v1.1.27），
    且**禁入两族一律不改写**（第七轮审计 A7：`_rejected_pair`）——基础表里已经没有
    这两族键，这道闸是给"下一次有人往 extra 里加『XX→关灯』"留的护栏。"""
    if not text:
        return text
    merged = dict(extra or {})
    merged.update(BASE_CORRECTIONS)  # 基础表优先（用户扩展只追加新键）
    for wrong in sorted(merged, key=len, reverse=True):
        right = merged[wrong]
        if _rejected_pair(wrong, right):
            continue
        if wrong and wrong in text:
            text = _replace_whole(text, wrong, right)
    return text
